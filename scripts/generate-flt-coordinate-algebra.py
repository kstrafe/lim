def hygienic_form(text):
    """Give colliding local binders fresh literal names; globals stay explicit.

    This is syntax authoring only. Lim still checks the saved term, including
    its no-shadowing rule, dependent binder scopes and all original obligations.
    """
    tokens=re.findall(r'[()]|[^()\s]+',text);position=0;counter=0;used=set(tokens)
    def parse():
        nonlocal position
        token=tokens[position];position+=1
        if token!='(':return token
        result=[]
        while tokens[position]!=')':result.append(parse())
        position+=1;return result
    tree=parse();assert position==len(tokens)
    def bind(items,env):
        nonlocal counter
        scope=dict(env);result=[]
        for name,ty in items:
            annotation=walk(ty,scope);fresh=name
            if name in scope:
                while fresh in used:
                    fresh=f'{name}-bound-{counter:04}';counter+=1
                used.add(fresh)
            result.append([fresh,annotation]);scope[name]=fresh
        return result,scope
    def walk(node,env):
        if isinstance(node,str):return env.get(node,node)
        if not node:return node
        tag=node[0]
        if tag in ['#pt-pi','#pt-lambda','#pt-sigma']:
            bs,scope=bind(node[1],env);return [tag,bs,walk(node[2],scope)]
        if tag=='#pt-use':return node
        if tag=='#pt-project':return [*node[:3],walk(node[3],env)]
        if tag=='#pt-construct':return [*node[:3],walk(node[3],env),node[4],walk(node[5],env)]
        if tag=='#pt-induct':return [*node[:3],*(walk(v,env) for v in node[3:])]
        return [walk(v,env) for v in node]
    if tree[0]=='#theorem':
        env={};result=tree[:2]
        for section in tree[2:]:
            if section[0]=='#parameters':
                bs,env=bind([v[1:] for v in section[1:]],env)
                result.append(['#parameters',*[[v[0],*pair] for v,pair in zip(section[1:],bs)]])
            else:result.append([section[0],*(walk(v,env) for v in section[1:])])
        tree=result
    elif tree[0]=='#math-definition':tree=[*tree[:3],walk(tree[3],{}),walk(tree[4],{})]
    elif tree[0]=='#math-inductive':
        bs,env=bind(tree[3],{});constructors=[]
        for name,fields in tree[5]:
            fs,_=bind(fields,env);constructors.append([name,fs])
        tree=[*tree[:3],bs,walk(tree[4],env),constructors]
    else:raise ValueError('unexpected native declaration')
    def render(node):return node if isinstance(node,str) else '('+' '.join(map(render,node))+')'
    return render(tree)

