#!/usr/bin/env python3
"""Author checked Lim signed residue casts and coefficient reduction proofs.

The emitted terms use the existing native kernel. This script provides no
trusted judgments and is not needed to check the resulting Lim files.
"""
import argparse
import importlib.util
import re
from pathlib import Path

_spec = importlib.util.spec_from_file_location(
    'finite_residue_syntax', Path(__file__).with_name('generate-flt-finite-residues.py'))
_syntax = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_syntax)
f, seq, app, use, eq, pi, lam = (_syntax.f, _syntax.seq, _syntax.app,
    _syntax.use, _syntax.eq, _syntax.pi, _syntax.lam)
N = '#pt-nat'

def call(name, *args):
    return app(use(name), *args) if args else use(name)

def definition(name, binders, result, body):
    return f('#math-definition', name, '()', pi(binders, result), lam(binders, body))

def generated_sources():
    outputs = {}
    root = Path(__file__).resolve().parent.parent / 'theorems' / 'flt'
    aliases = {'add': '../fermat_statement', 'multiply': '../fermat_statement'}
    for module in ['equality', 'natural-order', 'natural-addition',
        'natural-multiplication-right', 'natural-multiplication', 'logical-decision', 'decidable-logic', 'natural-decision',
        'finite-residue-defs', 'finite-residue-operations',
        'finite-residue-congruence', 'finite-residue-arithmetic-laws',
        'finite-residue-nested-reduction', 'finite-residue-semiring',
        'finite-residue-negation', 'logical-connectives', 'integer-defs', 'integer-weierstrass-defs',
        'weierstrass-model-equivalence']:
        for name in re.findall(r'^\(#(?:theorem|math-definition|math-inductive) ([^\s()]+)',
                               (root / (module + '.lim')).read_text(), re.M):
            aliases[name] = module

    def write(module, comment, forms, source='zmod'):
        body = '\n\n'.join(forms) + '\n'
        names = re.findall(r'^\(#(?:theorem|math-definition|math-inductive) ([^\s()]+)', body, re.M)
        tokens = set(re.findall(r'[^()\s]+', body))
        header = ''
        if source == 'zmod':
            header = ('; Copyright (c) 2022 Eric Rodriguez. All rights reserved.\n'
                '; Released under Apache 2.0; see LICENSE.MATHLIB.\n'
                '; Mathematical source: pinned Mathlib Data/ZMod/Defs.lean.\n')
        elif source == 'affine':
            header = ('; Copyright (c) 2025 David Kurniadi Angdinata. All rights reserved.\n'
                '; Released under Apache 2.0; see LICENSE.MATHLIB.\n'
                '; Mathematical source: pinned Mathlib EllipticCurve/Affine/Basic.lean and Point.lean.\n')
        header += '; Generated by scripts/generate-flt-signed-residues.py; checked native proof terms.\n'
        imports = ''.join(f'(#alias {name} = ./{owner}.lim::{name})\n'
                          for name, owner in aliases.items() if name in tokens and owner != module)
        outputs[module] = header + comment + '\n' + imports + '\n' + body
        aliases.update({name: module for name in names})

    q, positive = 'modulus', 'positive-modulus'
    bs = [(q, N), (positive, call('less-than', '#pt-zero', q))]
    F = call('finite-residue', q)
    Z = call('finite-residue-zero', q, positive)
    O = call('finite-residue-one', q, positive)
    def V(x): return f('#pt-project', 'finite-residue', '0', x)
    def A(a, b): return call('finite-residue-add', q, positive, a, b)
    def M(a, b): return call('finite-residue-multiply', q, positive, a, b)
    def Neg(x): return call('finite-residue-negate', q, positive, x)
    def R(x): return call('finite-residue-of-natural', q, positive, x)
    def E(a, b): return eq(V(a), V(b))
    def refl(x): return _syntax.refl(V(x))
    def sym(a, b, h): return _syntax.sym(V(a), V(b), h)
    def trans(a, b, c, h, j): return _syntax.trans(V(a), V(b), V(c), h, j)
    def chain(xs, hs): return _syntax.chain([V(x) for x in xs], hs)
    def lemma(name, params, statement, proof):
        return _syntax.theorem(name, bs + params, statement, proof)
    def law(name, *args): return call('finite-residue-' + name, q, positive, *args)
    def ac(a, b, c, d, h, j): return law('add-congruent', a, b, c, d, h, j)
    def mc(a, b, c, d, h, j): return law('multiply-congruent', a, b, c, d, h, j)
    def nc(a, b, h): return law('negate-congruent', a, b, h)
    def assoc(a, b, c): return law('add-associative', a, b, c)
    def comm(a, b): return law('add-commutative', a, b)
    a, b, c, d = 'first', 'second', 'third', 'fourth'
    four = [(x, F) for x in [a, b, c, d]]

    forms = []
    for name, op, raw in [('add', A, _syntax.add), ('multiply', M, _syntax.mul)]:
        h, j = 'first-equation', 'second-equation'
        path = _syntax.chain([raw(V(a), V(b)), raw(V(c), V(b)), raw(V(c), V(d))], [
            _syntax.cong(lam([('left-operand', N)], raw('left-operand', V(b))), V(a), V(c), h),
            _syntax.cong(lam([('right-operand', N)], raw(V(c), 'right-operand')), V(b), V(d), j)])
        proof = call('finite-reduction-congruent', q, positive, raw(V(a), V(b)), raw(V(c), V(d)), path)
        forms.append(lemma('finite-residue-' + name + '-congruent', four + [(h, E(a, c)), (j, E(b, d))],
            E(op(a, b), op(c, d)), proof))
    predecessor = call('predecessor', q)
    aliases['predecessor'] = 'natural-successor'
    raw_a, raw_b = _syntax.mul(predecessor, V(a)), _syntax.mul(predecessor, V(b))
    proof = call('finite-reduction-congruent', q, positive, raw_a, raw_b,
        _syntax.cong(lam([('negative-operand', N)], _syntax.mul(predecessor, 'negative-operand')), V(a), V(b), 'equation'))
    forms.append(lemma('finite-residue-negate-congruent', four[:2] + [('equation', E(a, b))], E(Neg(a), Neg(b)), proof))
    forms.append(lemma('finite-residue-zero-value', [], eq(V(Z), '#pt-zero'),
        call('finite-reduction-small', q, positive, '#pt-zero', positive)))
    proof = _syntax.trans(V(A(a, Neg(a))), '#pt-zero', V(Z), law('add-inverse', a),
        _syntax.sym(V(Z), '#pt-zero', law('zero-value')))
    forms.append(lemma('finite-residue-add-inverse-zero', four[:1], E(A(a, Neg(a)), Z), proof))
    forms.append(lemma('finite-residue-add-inverse-left-zero', four[:1], E(A(Neg(a), a), Z),
        trans(A(Neg(a), a), A(a, Neg(a)), Z, comm(Neg(a), a), law('add-inverse-zero', a))))
    forms.append(lemma('finite-residue-add-zero-left', four[:1], E(A(Z, a), a),
        trans(A(Z, a), A(a, Z), a, comm(Z, a), law('add-identity', a))))
    write('finite-residue-congruence-laws', '; Equality of representatives respects every actual residue operation.\n'
        '; Relate the computed zero value and inverse laws to the zero record.', forms)

    h = 'sum-equation'; na = Neg(a)
    path = chain([b, A(Z, b), A(A(na, a), b), A(na, A(a, b)), A(na, A(a, c)), A(A(na, a), c), A(Z, c), c], [
        sym(A(Z, b), b, law('add-zero-left', b)),
        ac(Z, b, A(na, a), b, sym(A(na, a), Z, law('add-inverse-left-zero', a)), refl(b)),
        assoc(na, a, b), ac(na, A(a, b), na, A(a, c), refl(na), h),
        sym(A(A(na, a), c), A(na, A(a, c)), assoc(na, a, c)),
        ac(A(na, a), c, Z, c, law('add-inverse-left-zero', a), refl(c)),
        law('add-zero-left', c)])
    forms = [lemma('finite-residue-add-cancel-left', four[:3] + [(h, E(A(a, b), A(a, c)))], E(b, c), path)]
    path = chain([A(c, a), A(a, c), A(b, c), A(c, b)], [comm(c, a), h, comm(b, c)])
    forms.append(lemma('finite-residue-add-cancel-right', four[:3] + [(h, E(A(a, c), A(b, c)))], E(a, b),
        law('add-cancel-left', c, a, b, path)))
    path = trans(A(a, b), Z, A(a, Neg(a)), 'inverse-equation', sym(A(a, Neg(a)), Z, law('add-inverse-zero', a)))
    forms.append(lemma('finite-residue-negate-unique', four[:2] + [('inverse-equation', E(A(a, b), Z))], E(b, Neg(a)),
        law('add-cancel-left', a, b, Neg(a), path)))
    proof = law('negate-unique', Z, Z, law('add-identity', Z))
    forms.append(lemma('finite-residue-negate-zero', [], E(Neg(Z), Z), sym(Z, Neg(Z), proof)))
    proof = law('negate-unique', Neg(a), a, law('add-inverse-left-zero', a))
    forms.append(lemma('finite-residue-negate-involution', four[:1], E(Neg(Neg(a)), a), sym(a, Neg(Neg(a)), proof)))
    write('finite-residue-cancellation', '; Cancel additions using the proved computed inverse, including\n'
        '; the unit modulus. Uniqueness and involution need no nonzero axiom.', forms)

    path = chain([A(a, A(b, c)), A(A(a, b), c), A(A(b, a), c), A(b, A(a, c))], [
        sym(A(A(a, b), c), A(a, A(b, c)), assoc(a, b, c)),
        ac(A(a, b), c, A(b, a), c, comm(a, b), refl(c)), assoc(b, a, c)])
    forms = [lemma('finite-residue-add-swap-inner', four[:3], E(A(a, A(b, c)), A(b, A(a, c))), path)]
    path = chain([A(A(a, b), A(c, d)), A(a, A(b, A(c, d))), A(a, A(c, A(b, d))), A(A(a, c), A(b, d))], [
        assoc(a, b, A(c, d)),
        ac(a, A(b, A(c, d)), a, A(c, A(b, d)), refl(a), law('add-swap-inner', b, c, d)),
        sym(A(A(a, c), A(b, d)), A(a, A(c, A(b, d))), assoc(a, c, A(b, d)))])
    forms.append(lemma('finite-residue-add-shuffle-four', four, E(A(A(a, b), A(c, d)), A(A(a, c), A(b, d))), path))
    target = A(Neg(a), Neg(b))
    path = chain([A(A(a, b), target), A(A(a, Neg(a)), A(b, Neg(b))), A(Z, Z), Z], [
        law('add-shuffle-four', a, b, Neg(a), Neg(b)),
        ac(A(a, Neg(a)), A(b, Neg(b)), Z, Z, law('add-inverse-zero', a), law('add-inverse-zero', b)),
        law('add-identity', Z)])
    unique = law('negate-unique', A(a, b), target, path)
    forms.append(lemma('finite-residue-negate-add', four[:2], E(Neg(A(a, b)), target), sym(target, Neg(A(a, b)), unique)))
    write('finite-residue-additive-rearrangement', '; Explicit group rearrangements and the inverse of a sum, derived\n'
        '; from the checked associativity, commutativity and cancellation laws.', forms)

    forms = []
    raw = _syntax.mul(V(a), '#pt-zero')
    proof = _syntax.chain([V(M(a, Z)), V(R(raw)), V(Z)], [
        call('finite-reduction-product-right', q, positive, V(a), '#pt-zero'),
        call('finite-reduction-congruent', q, positive, raw, '#pt-zero', call('multiply-zero-right', V(a)))])
    forms.append(lemma('finite-residue-multiply-zero-right', four[:1], E(M(a, Z), Z), proof))
    forms.append(lemma('finite-residue-multiply-zero-left', four[:1], E(M(Z, a), Z),
        trans(M(Z, a), M(a, Z), Z, law('multiply-commutative', Z, a), law('multiply-zero-right', a))))
    proof = chain([M(A(a, b), c), M(c, A(a, b)), A(M(c, a), M(c, b)), A(M(a, c), M(b, c))], [
        law('multiply-commutative', A(a, b), c), law('distributive', c, a, b),
        ac(M(c, a), M(c, b), M(a, c), M(b, c), law('multiply-commutative', c, a), law('multiply-commutative', c, b))])
    forms.append(lemma('finite-residue-distribute-first', four[:3], E(M(A(a, b), c), A(M(a, c), M(b, c))), proof))
    inverse = chain([A(M(a, b), M(Neg(a), b)), M(A(a, Neg(a)), b), M(Z, b), Z], [
        sym(M(A(a, Neg(a)), b), A(M(a, b), M(Neg(a), b)), law('distribute-first', a, Neg(a), b)),
        mc(A(a, Neg(a)), b, Z, b, law('add-inverse-zero', a), refl(b)), law('multiply-zero-left', b)])
    forms.append(lemma('finite-residue-multiply-negate-first', four[:2], E(M(Neg(a), b), Neg(M(a, b))),
        law('negate-unique', M(a, b), M(Neg(a), b), inverse)))
    proof = chain([M(a, Neg(b)), M(Neg(b), a), Neg(M(b, a)), Neg(M(a, b))], [
        law('multiply-commutative', a, Neg(b)), law('multiply-negate-first', b, a),
        nc(M(b, a), M(a, b), law('multiply-commutative', b, a))])
    forms.append(lemma('finite-residue-multiply-negate-second', four[:2], E(M(a, Neg(b)), Neg(M(a, b))), proof))
    proof = chain([M(Neg(a), Neg(b)), Neg(M(a, Neg(b))), Neg(Neg(M(a, b))), M(a, b)], [
        law('multiply-negate-first', a, Neg(b)), nc(M(a, Neg(b)), Neg(M(a, b)), law('multiply-negate-second', a, b)),
        law('negate-involution', M(a, b))])
    forms.append(lemma('finite-residue-multiply-negate-both', four[:2], E(M(Neg(a), Neg(b)), M(a, b)), proof))
    write('finite-residue-multiplicative-signs', '; Actual zero products, two-sided distributivity and multiplication\n'
        '; by computed inverses. Every sign law follows from the native group laws.', forms)

    def D(a, b): return call('finite-residue-difference', q, positive, a, b)
    forms = [definition('finite-residue-difference', bs + four[:2], F, A(a, Neg(b)))]
    forms.append(lemma('finite-residue-difference-congruent', four + [('first-equation', E(a, c)), ('second-equation', E(b, d))],
        E(D(a, b), D(c, d)), ac(a, Neg(b), c, Neg(d), 'first-equation', nc(b, d, 'second-equation'))))
    forms.append(lemma('finite-residue-difference-self', four[:1], E(D(a, a), Z), law('add-inverse-zero', a)))
    proof = trans(D(a, Z), A(a, Z), a,
        ac(a, Neg(Z), a, Z, refl(a), law('negate-zero')), law('add-identity', a))
    forms.append(lemma('finite-residue-difference-zero-right', four[:1], E(D(a, Z), a), proof))
    forms.append(lemma('finite-residue-difference-zero-left', four[:1], E(D(Z, a), Neg(a)), law('add-zero-left', Neg(a))))
    proof = chain([A(D(a, b), b), A(a, A(Neg(b), b)), A(a, Z), a], [
        assoc(a, Neg(b), b), ac(a, A(Neg(b), b), a, Z, refl(a), law('add-inverse-left-zero', b)), law('add-identity', a)])
    forms.append(lemma('finite-residue-difference-add-denominator', four[:2], E(A(D(a, b), b), a), proof))
    proof = trans(A(D(a, b), A(b, c)), A(A(D(a, b), b), c), A(a, c),
        sym(A(A(D(a, b), b), c), A(D(a, b), A(b, c)), assoc(D(a, b), b, c)),
        ac(A(D(a, b), b), c, a, c, law('difference-add-denominator', a, b), refl(c)))
    forms.append(lemma('finite-residue-difference-add-two', four[:3], E(A(D(a, b), A(b, c)), A(a, c)), proof))
    proof = trans(A(D(a, b), D(c, d)), A(A(a, c), A(Neg(b), Neg(d))), D(A(a, c), A(b, d)),
        law('add-shuffle-four', a, Neg(b), c, Neg(d)),
        ac(A(a, c), A(Neg(b), Neg(d)), A(a, c), Neg(A(b, d)), refl(A(a, c)),
            sym(Neg(A(b, d)), A(Neg(b), Neg(d)), law('negate-add', b, d))))
    forms.append(lemma('finite-residue-difference-sum', four, E(A(D(a, b), D(c, d)), D(A(a, c), A(b, d))), proof))
    proof = chain([Neg(D(a, b)), A(Neg(a), Neg(Neg(b))), A(Neg(a), b), D(b, a)], [
        law('negate-add', a, Neg(b)), ac(Neg(a), Neg(Neg(b)), Neg(a), b, refl(Neg(a)), law('negate-involution', b)), comm(Neg(a), b)])
    forms.append(lemma('finite-residue-difference-negate', four[:2], E(Neg(D(a, b)), D(b, a)), proof))
    write('finite-residue-differences', '; Signed formal differences in the actual computed residue ring.\n'
        '; Addition, negation and denominator cancellation use no quotient axiom.', forms)

    common = A(b, d)
    first_path = law('difference-add-two', a, b, d)
    second_path = trans(A(D(c, d), common), A(D(c, d), A(d, b)), A(c, b),
        ac(D(c, d), common, D(c, d), A(d, b), refl(D(c, d)), comm(b, d)), law('difference-add-two', c, d, b))
    combined = chain([A(D(a, b), common), A(a, d), A(c, b), A(D(c, d), common)], [
        first_path, 'cross-equation', sym(A(D(c, d), common), A(c, b), second_path)])
    proof = law('add-cancel-right', D(a, b), D(c, d), common, combined)
    forms = [lemma('finite-residue-difference-cross-congruent', four + [('cross-equation', E(A(a, d), A(c, b)))], E(D(a, b), D(c, d)), proof)]
    x, y, z, w = M(a, c), Neg(M(b, c)), Neg(M(a, d)), M(b, d)
    unexpanded = A(M(D(a, b), c), M(D(a, b), Neg(d)))
    expanded = A(A(M(a, c), M(Neg(b), c)), A(M(a, Neg(d)), M(Neg(b), Neg(d))))
    mapped = A(A(x, y), A(z, w))
    proof = chain([M(D(a, b), D(c, d)), unexpanded, expanded, mapped], [
        law('distributive', D(a, b), c, Neg(d)),
        ac(M(D(a, b), c), M(D(a, b), Neg(d)), A(M(a, c), M(Neg(b), c)), A(M(a, Neg(d)), M(Neg(b), Neg(d))),
            law('distribute-first', a, Neg(b), c), law('distribute-first', a, Neg(b), Neg(d))),
        ac(A(M(a, c), M(Neg(b), c)), A(M(a, Neg(d)), M(Neg(b), Neg(d))), A(x, y), A(z, w),
            ac(M(a, c), M(Neg(b), c), x, y, refl(x), law('multiply-negate-first', b, c)),
            ac(M(a, Neg(d)), M(Neg(b), Neg(d)), z, w, law('multiply-negate-second', a, d), law('multiply-negate-both', b, d)))])
    forms.append(lemma('finite-residue-difference-product-expand', four, E(M(D(a, b), D(c, d)), mapped), proof))
    target = D(A(M(a, c), M(b, d)), A(M(a, d), M(b, c)))
    proof = chain([M(D(a, b), D(c, d)), mapped, A(A(x, y), A(w, z)), A(A(x, w), A(y, z)), A(A(x, w), A(z, y)), target], [
        law('difference-product-expand', a, b, c, d),
        ac(A(x, y), A(z, w), A(x, y), A(w, z), refl(A(x, y)), comm(z, w)),
        law('add-shuffle-four', x, y, w, z),
        ac(A(x, w), A(y, z), A(x, w), A(z, y), refl(A(x, w)), comm(y, z)),
        ac(A(x, w), A(z, y), A(x, w), Neg(A(M(a, d), M(b, c))), refl(A(x, w)),
            sym(Neg(A(M(a, d), M(b, c))), A(z, y), law('negate-add', M(a, d), M(b, c))))])
    forms.append(lemma('finite-residue-difference-product', four, E(M(D(a, b), D(c, d)), target), proof))
    write('finite-residue-difference-congruence', '; The cross-addition relation on formal differences gives the\n'
        '; same residue. Products follow by checked expansion and sign laws.', forms)

    I = call('integer')
    def ip(x): return f('#pt-project', 'integer', '0', x)
    def im(x): return f('#pt-project', 'integer', '1', x)
    def C(x): return call('finite-residue-of-integer', q, positive, x)
    def Dcong(a, b, c, d, h, j): return law('difference-congruent', a, b, c, d, h, j)
    x, y, number = 'integer-first', 'integer-second', 'natural-number'
    forms = [definition('finite-residue-of-integer', bs + [(x, I)], F, D(R(ip(x)), R(im(x))))]
    nat = call('integer-of-natural', number)
    forms.append(lemma('finite-residue-integer-natural', [(number, N)], E(C(nat), R(number)), law('difference-zero-right', R(number))))
    negnat = call('integer-negative-natural', number)
    forms.append(lemma('finite-residue-integer-negative-natural', [(number, N)], E(C(negnat), Neg(R(number))), law('difference-zero-left', R(number))))
    negx = call('integer-negate', x)
    proof = sym(Neg(C(x)), C(negx), law('difference-negate', R(ip(x)), R(im(x))))
    forms.append(lemma('finite-residue-integer-negate', [(x, I)], E(C(negx), Neg(C(x))), proof))
    p1, n1, p2, n2 = ip(x), im(x), ip(y), im(y)
    left, right = _syntax.add(p1, n2), _syntax.add(p2, n1)
    cross = chain([A(R(p1), R(n2)), R(left), R(right), A(R(p2), R(n1))], [
        sym(R(left), A(R(p1), R(n2)), call('finite-reduction-sum', q, positive, p1, n2)),
        call('finite-reduction-congruent', q, positive, left, right, 'integer-equation'),
        call('finite-reduction-sum', q, positive, p2, n1)])
    proof = law('difference-cross-congruent', R(p1), R(n1), R(p2), R(n2), cross)
    forms.append(lemma('finite-residue-integer-congruent', [(x, I), (y, I), ('integer-equation', call('integer-equal', x, y))], E(C(x), C(y)), proof))
    forms.append(lemma('finite-residue-integer-zero', [], E(C(call('integer-zero')), Z),
        law('integer-natural', '#pt-zero')))
    forms.append(lemma('finite-residue-integer-one', [], E(C(call('integer-one')), O),
        law('integer-natural', f('#pt-succ', '#pt-zero'))))
    write('finite-residue-integer-cast', '; The signed cast computes the difference of the two natural\n'
        '; representatives. Integer cross-addition equivalence is proved\n'
        '; to preserve the result; proof terms never treat formal pairs as canonical integers.', forms)

    raw = _syntax.add(_syntax.mul(a, b), _syntax.mul(c, d))
    proof = trans(R(raw), A(R(_syntax.mul(a, b)), R(_syntax.mul(c, d))), A(M(R(a), R(b)), M(R(c), R(d))),
        call('finite-reduction-sum', q, positive, _syntax.mul(a, b), _syntax.mul(c, d)),
        ac(R(_syntax.mul(a, b)), R(_syntax.mul(c, d)), M(R(a), R(b)), M(R(c), R(d)),
            call('finite-reduction-product', q, positive, a, b), call('finite-reduction-product', q, positive, c, d)))
