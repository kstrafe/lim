    forms=[theorem('polynomial-root-division-equation',params+[(p,L)],goal(p),induct(p,lam([('subject',L)],goal('subject')),zproof,step))]
    write('polynomial-root-division-equation','; For every finite polynomial compute Q,r\n; and prove p=(X-root)*Q+[r]. Arbitrary trailing zeros and\n; zero divisors are retained by coefficientwise equivalence.',forms)

    goal=lambda p:E(rresult(p),ev(p))
