    forms=[theorem('polynomial-root-step-equation',params+[(h,R),(t,L),(q,L),(r,R),('tail-equation',pe(t,old))],pe(cons(h,t),pa(pm(D,newq),const(newr))),proof)]
    write('polynomial-root-step-equation','; Derive the actual Horner division step\n; from the proved local identity and polynomial ring laws.\n; The quotient/remainder recurrence is not a supplied equation.',forms)

    goal=lambda p:pe(p,pa(pm(D,qresult(p)),const(rresult(p))))
