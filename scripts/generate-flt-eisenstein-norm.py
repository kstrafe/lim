#!/usr/bin/env python3
"""Author checked scalar identities for Eisenstein conjugation and the norm.

Only existing integer ring proofs are used. This optional authoring tool is
not part of compilation and grants no mathematical authority to its output.
The inherited coefficient, source-size and helper bounds remain unchanged.
"""
import argparse
import importlib.util
import re
import sys
from pathlib import Path

_spec=importlib.util.spec_from_file_location('flt_eisenstein_ring_authoring',Path(__file__).with_name('generate-flt-eisenstein-algebra.py'))
_ring=importlib.util.module_from_spec(_spec)
sys.modules[_spec.name]=_ring
_spec.loader.exec_module(_ring)
add,mul,negative,Eisenstein=_ring.add,_ring.mul,_ring.negative,_ring.Eisenstein

class NormBuilder(_ring.IntegerPolynomialBuilder):
    def theorem(self,name,variables,left,right):
        super().theorem(name,variables,left,right)
        self.origins=[f'scripts/generate-flt-eisenstein-norm.py:{sys._getframe(1).f_lineno}']
    def source(self):
        return super().source().replace('scripts/generate-flt-eisenstein-algebra.py','scripts/generate-flt-eisenstein-norm.py')

def conjugate(x):return Eisenstein(add(x.real,negative(x.omega)),negative(x.omega))
def square(x):return mul(x,x)
def norm(x):return add(add(square(x.real),negative(mul(x.real,x.omega))),square(x.omega))

def identities():
    a,b,c,d='first-real','first-omega','second-real','second-omega'
    x,y=Eisenstein(a,b),Eisenstein(c,d)
    result=[]
    for label,variables,left,right in [
        ('conjugate-involution',(a,b),conjugate(conjugate(x)),x),
        ('conjugate-add',(a,b,c,d),conjugate(x+y),conjugate(x)+conjugate(y)),
        ('conjugate-product',(a,b,c,d),conjugate(x*y),conjugate(x)*conjugate(y)),
        ('product-conjugate',(a,b),x*conjugate(x),Eisenstein(norm(x),0)),
    ]:
        for coordinate in ['real','omega']:
            result.append((label+'-'+coordinate,variables,getattr(left,coordinate),getattr(right,coordinate)))
    result += [
        ('norm-conjugate',(a,b),norm(conjugate(x)),norm(x)),
        ('norm-negative',(a,b),norm(-x),norm(x)),
        ('norm-scalar',(a,),norm(Eisenstein(a,0)),square(a)),
        ('norm-four-square-omega',(a,b),mul(4,norm(x)),add(square(add(mul(2,a),negative(b))),mul(3,square(b)))),
        ('norm-four-square-real',(a,b),mul(4,norm(x)),add(mul(3,square(a)),square(add(a,negative(mul(2,b)))))),
        ('norm-difference-square',(a,b),norm(x),add(square(add(a,negative(b))),mul(a,b))),
    ]
    return result + [('lambda-multiply',(a,b),norm(Eisenstein(negative(1),1)*x),mul(3,norm(x)))]

def generate_sources():
    result={}
    for label,variables,left,right in identities():
        name='eisenstein-norm-scalar-'+label
        builder=NormBuilder(name)
        builder.theorem(name,variables,left,right)
        result[name+'.lim']=builder.source()
    return result

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    root=Path(__file__).resolve().parent.parent/'theorems/flt'
    def tokens(text):return re.findall(r'[()]|[^()\s]+',re.sub(r';[^\n]*','',text))
    def origins(text):return [l.strip() for l in text.splitlines() if l.strip().startswith('; scripts/generate-flt-eisenstein-norm.py:')]
    generated=generate_sources()
    for path in root.glob('eisenstein-norm-scalar-*.lim'):
        if path.name not in generated:
            if not path.read_text().startswith('; Generated by scripts/generate-flt-eisenstein-norm.py;'):raise SystemExit(f'{path.name}: unexpected non-generated source')
            if args.check:raise SystemExit(f'{path.name}: stale generated source')
            path.unlink()
    for name,source in generated.items():
        path=root/name;current=path.read_text() if path.exists() else None
        matches=current is not None and tokens(current)==tokens(source) and origins(current)==origins(source)
        if args.check:
            if not matches:raise SystemExit(f'{name}: source differs; regenerate with this script')
        elif not matches:path.write_text(source)

if __name__=='__main__':main()
