#!/usr/bin/env python3
"""Author native Weierstrass norm degree and obstruction proofs.

Only syntax is produced here. Lim checks the saved definitions, induction
terms and each application of a ring law without trusting this writer.
"""
import argparse
import importlib.util
import re
import sys
from collections import namedtuple
from pathlib import Path

spec = importlib.util.spec_from_file_location(
    'quadratic_syntax', Path(__file__).with_name('generate-flt-coordinate-algebra.py'))
s = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = s
spec.loader.exec_module(s)
f, seq, app, use, pi, lam, theorem = s.f, s.seq, s.app, s.use, s.pi, s.lam, s.theorem
definition, call, project, equal, refl = s.definition, s.call, s.project, s.equal, s.refl
N, PROP, TYPE, ZERO = s.N, s.PROP, s.TYPE, s.ZERO

natural_spec = importlib.util.spec_from_file_location('norm_natural_authoring', Path(__file__).with_name('generate-flt-semiring.py'))
natural = importlib.util.module_from_spec(natural_spec)
sys.modules[natural_spec.name] = natural
natural_spec.loader.exec_module(natural)


def generated_sources():
    root = Path(__file__).resolve().parent.parent / 'theorems' / 'flt'
    aliases = {}
    for path in sorted(root.glob('*.lim')):
        if path.stem.startswith(('coordinate-norm-degree-',)):
            continue
        for name in re.findall(r'^\(#(?:theorem|math-definition|math-inductive) ([^\s()]+)', path.read_text(), re.M):
            aliases.setdefault(name, set()).add(path.stem)
    for name in ['add', 'multiply', 'power']:
        aliases[name] = {'../fermat_statement'}
    outputs = {}
    notice = ('; Copyright (c) 2018 Chris Hughes and 2025 David Kurniadi Angdinata.\n'
              '; Released under Apache 2.0; see LICENSE.MATHLIB.\n'
              '; Adapted source: pinned Mathlib Affine/Point.lean:409-470.\n'
              '; All polynomial, coefficient-domain and index facts are proved.\n'
              '; Generated by scripts/generate-flt-norm-degrees.py; checked native terms.\n')

    def write(module, comment, forms):
        forms = [s.hygienic_form(form) for form in forms]
        body = '\n\n'.join(forms) + '\n'
        tokens = set(re.findall(r'[^()\s]+', body))
        names = re.findall(r'^\(#(?:theorem|math-definition|math-inductive) ([^\s()]+)', body, re.M)
        needed = {name: owners for name, owners in aliases.items() if name in tokens and name not in names}
        for name, owners in needed.items():
            if len(owners) != 1:
                raise ValueError(f'ambiguous dependency: {name}: {owners}')
        imports = ''.join(f'(#alias {name} = ./{next(iter(owners))}.lim::{name})\n'
                          for name, owners in sorted(needed.items()))
        outputs[module] = notice + comment + '\n' + imports + '\n' + body
        for name in names:
            aliases[name] = {module}

    R, ring = 'Carrier', 'coefficient-ring'
    base = [(R, TYPE), (ring, call('commutative-ring', R))]
    op = lambda label, *args: call('ring-' + label, R, ring, *args)
    E = lambda a, b: op('equal', a, b)
    A = lambda a, b: op('add', a, b)
    M = lambda a, b: op('multiply', a, b)
    Neg = lambda a: op('negate', a)
    Z, O = op('zero'), op('one')
    rr = lambda a: op('reflexive', a)
    ss = lambda a, b, h: op('symmetric', a, b, h)
    tt = lambda a, b, c, h, j: op('transitive', a, b, c, h, j)
    ac = lambda a, b, c, d, h, j: op('add-congruent', a, b, c, d, h, j)
    mc = lambda a, b, c, d, h, j: op('multiply-congruent', a, b, c, d, h, j)
    nc = lambda a, b, h: op('negate-congruent', a, b, h)
    L = call('finite-list', R)
    nil = lambda: f('#pt-construct', 'finite-list', '()', seq([R]), 'nil', '()')
    cons = lambda h, t: f('#pt-construct', 'finite-list', '()', seq([R]), 'cons', seq([h, t]))
    const = lambda c: cons(c, nil())
    linear = lambda p, q: cons(p, const(q))
    induct = lambda xs, motive, z, step: f('#pt-induct', 'finite-list', '()', seq([R]), motive, seq([z, step]), xs)
    plaw = lambda label, *args: call('ring-polynomial-' + label, R, ring, *args)
    pe = lambda a, b: plaw('equal', a, b)
    pa = lambda a, b: plaw('add', a, b)
    pm = lambda a, b: plaw('multiply', a, b)
    pn = lambda a: plaw('negate', a)
    px = lambda a: plaw('shift', a)
    ps = lambda a, b: plaw('scale', a, b)
    pr = lambda a: plaw('reflexive', a)
    psy = lambda a, b, h: plaw('symmetric', a, b, h)
    ptr = lambda a, b, c, h, j: plaw('transitive', a, b, c, h, j)
    pac = lambda a, b, c, d, h, j: plaw('add-congruent', a, b, c, d, h, j)
    def pchain(values, proofs):
        assert len(values) == len(proofs) + 1
        result = proofs[-1]
        for i in range(len(proofs)-2, -1, -1):
            result = ptr(values[i], values[i+1], values[-1], proofs[i], result)
        return result

    succ=lambda n:f('#pt-succ',n)
    nad=lambda a,b:call('add',a,b)
    neq=lambda a,b:equal(N,a,b)
    nsy=lambda a,b,h:app(use('symmetry',['0']),N,a,b,h)
    sub=lambda prop,a,b,h,e:app(use('substitution',['0']),N,prop,a,b,h,e)
    neg=lambda p:pi([('denied-evidence',p)],'#pt-false')
    false=lambda prop,h:call('false-elimination',prop,h)
    both=lambda a,b:call('conjunction',a,b)
    pair=lambda a,b,h,j:call('conjunction-introduce',a,b,h,j)
    coeff=lambda p,n:plaw('coefficient',p,n)
    support=lambda p,b:call('ring-polynomial-support-from',R,ring,p,b)
    degree=lambda p,d:call('ring-polynomial-degree-witness',R,ring,p,d)
    law=lambda label,*args:call('ring-polynomial-'+label,R,ring,*args)
    dp,dq,g='constant-degree','linear-degree','gap'
    ncong=lambda fn,a,b,h:app(use('congruence',['0','0']),N,N,fn,a,b,h)
    ntrans=lambda a,b,c,h,j:app(use('transitivity',['0']),N,a,b,c,h,j)
    one,three='(#pt-numeral 1)','(#pt-numeral 3)'
    double=lambda a:nad(a,a)
    cubic=lambda a:nad(double(a),three)
    cross=lambda a,b:succ(nad(nad(a,b),one))
    an,asn=natural.add,natural.successor
    adouble=lambda a:an(a,a)
    acubic=lambda a:an(adouble(a),3)
    across=lambda a,b:asn(an(an(a,b),1))
    def variables(x):return {x} if isinstance(x,str) else set() if isinstance(x,int) else set().union(*(variables(v) for v in x[1:]))
    identity_parameters={}
    identities=[
        ('cubic-successor',acubic(dq),an(adouble(asn(dq)),1)),
        ('low-square',an(adouble(an(dp,g)),1),an(asn(adouble(dp)),adouble(g))),
        ('low-cross-reorder',an(across(dp,dq),g),an(an(dq,2),an(dp,g))),
        ('low-cross-finish',an(an(dq,2),asn(dq)),acubic(dq)),
        ('high-cross',adouble(an(asn(asn(dq)),g)),an(across(an(asn(asn(dq)),g),dq),g)),
        ('high-cubic',adouble(an(asn(asn(dq)),g)),an(asn(acubic(dq)),adouble(g))),
        ('double-successor',adouble(asn(dp)),asn(asn(adouble(dp)))),
        ('cubic-at-least-three',acubic(dq),asn(asn(asn(adouble(dq))))) ]
    for label,left,right in identities:
        name='coordinate-norm-degree-'+label+'-identity'
        builder=natural.Builder();vs=tuple(sorted(variables(left)|variables(right)))
        builder.theorem(name,vs,left,right)
        write(name,'; Explicit Nat semiring derivations used to align support\n; bounds. The bounded writer supplies terms, not arithmetic authority.',builder.helpers+builder.theorems)
        identity_parameters[label]=vs
    identity=lambda label,env:call('coordinate-norm-degree-'+label+'-identity',*(env[v] for v in identity_parameters[label]))
    env={dp:dp,dq:dq,g:g}
    low=neq(succ(dq),nad(dp,g))
    high=neq(dp,nad(succ(succ(dq)),g))
    params=[(dp,N),(dq,N),(g,N)]
    middle=nad(double(succ(dq)),one)
    nextvalue=nad(double(nad(dp,g)),one)
    proof=ntrans(cubic(dq),middle,nad(succ(double(dp)),double(g)),identity('cubic-successor',env),
                 ntrans(middle,nextvalue,nad(succ(double(dp)),double(g)),ncong(lam([('degree-input',N)],nad(double('degree-input'),one)),succ(dq),nad(dp,g),'low-relation'),identity('low-square',env)))
    forms=[theorem('coordinate-norm-degree-low-square-gap',params+[('low-relation',low)],neq(cubic(dq),nad(succ(double(dp)),double(g))),proof)]
    a,b,c=nad(cross(dp,dq),g),nad(nad(dq,'(#pt-numeral 2)'),nad(dp,g)),nad(nad(dq,'(#pt-numeral 2)'),succ(dq))
    proof=ntrans(a,b,cubic(dq),identity('low-cross-reorder',env),
                 ntrans(b,c,cubic(dq),ncong(lam([('degree-input',N)],nad(nad(dq,'(#pt-numeral 2)'),'degree-input')),nad(dp,g),succ(dq),nsy(succ(dq),nad(dp,g),'low-relation')),identity('low-cross-finish',env)))
    forms.append(theorem('coordinate-norm-degree-low-cross-gap',params+[('low-relation',low)],neq(cubic(dq),nad(cross(dp,dq),g)),nsy(a,cubic(dq),proof)))
    x=nad(succ(succ(dq)),g)
    proof=ntrans(double(dp),double(x),nad(cross(dp,dq),g),ncong(lam([('degree-input',N)],double('degree-input')),dp,x,'high-relation'),
                 ntrans(double(x),nad(cross(x,dq),g),nad(cross(dp,dq),g),identity('high-cross',env),
                    ncong(lam([('degree-input',N)],nad(cross('degree-input',dq),g)),x,dp,nsy(dp,x,'high-relation'))))
    forms.append(theorem('coordinate-norm-degree-high-cross-gap',params+[('high-relation',high)],neq(double(dp),nad(cross(dp,dq),g)),proof))
    proof=ntrans(double(dp),double(x),nad(succ(cubic(dq)),double(g)),ncong(lam([('degree-input',N)],double('degree-input')),dp,x,'high-relation'),identity('high-cubic',env))
    forms.append(theorem('coordinate-norm-degree-high-cubic-gap',params+[('high-relation',high)],neq(double(dp),nad(succ(cubic(dq)),double(g))),proof))
    write('coordinate-norm-degree-index-gaps','; The actual low/high input-degree relations yield explicit\n; nonnegative support gaps for both lower norm terms. Degree0 is retained;\n; equality boundaries use gap0. Every index equation is proved in Nat.',forms)

    # Exhaustiveness is used only in Prop. No coefficient decision or new
    # excluded-middle axiom is required for this negative elimination rule.
    p,q='polynomial','other-polynomial';h,t,ih='head','tail','tail-elimination'
    zero_ref=lambda p:neg(pe(p,nil()))
    degree_ref=lambda p:pi([('leading-degree',N),('leading-certificate',degree(p,'leading-degree'))],'#pt-false')
    goal=lambda p:pi([('zero-refutation',zero_ref(p)),('degree-refutation',degree_ref(p))],'#pt-false')
    head_nonzero=lam([('zero-head',E(h,Z))],app('zero-refutation',ptr(cons(h,t),px(nil()),nil(),
        plaw('cons-congruent',h,Z,t,nil(),'zero-head','zero-tail'),plaw('shift-nil'))))
    zerotail=lam([('zero-tail',pe(t,nil()))],app('degree-refutation',ZERO,law('degree-cons-zero',h,t,head_nonzero,'zero-tail')))
    leadingtail=lam([('tail-degree',N),('tail-certificate',degree(t,'tail-degree'))],
                    app('degree-refutation',succ('tail-degree'),law('degree-cons-successor',h,t,'tail-degree','tail-certificate')))
    step=lam([(h,R),(t,L),(ih,goal(t))],lam([('zero-refutation',zero_ref(cons(h,t))),('degree-refutation',degree_ref(cons(h,t)))],app(ih,zerotail,leadingtail)))
    proof=app(induct(p,lam([('selected-polynomial',L)],goal('selected-polynomial')),lam([('zero-refutation',zero_ref(nil())),('degree-refutation',degree_ref(nil()))],app('zero-refutation',pr(nil()))),step),'zero-refutation','degree-refutation')
    forms=[theorem('coordinate-norm-degree-exhaustive-elimination',base+[(p,L),('zero-refutation',zero_ref(p)),('degree-refutation',degree_ref(p))],'#pt-false',proof)]
    write('coordinate-norm-degree-exhaustive','; If zero and every possible leading-degree case both\n; contradict a claim, that claim is false. Structural list induction\n; proves this negative elimination rule without a zero-decision oracle\n; or a new excluded-middle axiom for the coefficient carrier.',forms)

    # Natural degree branching: dp<=dq+1, or dp>=dq+2, represented by gaps.
    exists_low=app(use('exists',['0']),N,lam([(g,N)],low))
    exists_high=app(use('exists',['0']),N,lam([(g,N)],high))
    alternative=call('disjunction',exists_low,exists_high)
    ctor=lambda pred,w,h:f('#pt-construct','exists','(0)',seq([N,pred]),'introduce',seq([w,h]))
    lt=lambda a,b:call('less-than',a,b)
    less=lt(dp,succ(dq));more=lt(succ(dq),dp)
    lowpred=lam([(g,N)],low);highpred=lam([(g,N)],high)
    lesspred=lam([(g,N)],neq(succ(dq),nad(succ(dp),g)))
    path=ntrans(succ(dq),nad(succ(dp),g),nad(dp,succ(g)),'less-position',nsy(nad(dp,succ(g)),nad(succ(dp),g),call('add-successor-right',dp,g)))
    lessproof=f('#pt-induct','exists','(0)',seq([N,lesspred]),lam([('comparison-certificate',less)],alternative),
                seq([lam([(g,N),('less-position',neq(succ(dq),nad(succ(dp),g)))],call('disjunction-left',exists_low,exists_high,ctor(lowpred,succ(g),path)))]),'less-comparison')
    equalpath=ntrans(succ(dq),dp,nad(dp,ZERO),nsy(dp,succ(dq),'equal-comparison'),nsy(nad(dp,ZERO),dp,call('add-zero-right',dp)))
    equalproof=call('disjunction-left',exists_low,exists_high,ctor(lowpred,ZERO,equalpath))
    highproof=call('disjunction-right',exists_low,exists_high,'more-comparison')
    remaining=call('disjunction',neq(dp,succ(dq)),more)
    proof=call('disjunction-eliminate',less,remaining,alternative,lam([('less-comparison',less)],lessproof),
        lam([('other-comparison',remaining)],call('disjunction-eliminate',neq(dp,succ(dq)),more,alternative,
            lam([('equal-comparison',neq(dp,succ(dq)))],equalproof),lam([('more-comparison',more)],highproof),'other-comparison')),call('natural-trichotomy',dp,succ(dq)))
    forms=[theorem('coordinate-norm-degree-gap-dichotomy',[(dp,N),(dq,N)],alternative,proof)]
    write('coordinate-norm-degree-dichotomy','; Construct actual gap witnesses for both exhaustive\n; degree-order branches, using proved Nat trichotomy and its gap\n; definition. The dp=dq+1 and dp=dq+2 boundaries remain explicit.',forms)

    structure='coefficient-domain'
    domainparams=base+[(structure,law('domain-data'))]
    coefficients=['a1','a2','a3','a4','a6']
    wparams=base+[(name,R) for name in coefficients]
    wdomain=domainparams+[(name,R) for name in coefficients]
    wargs=(R,ring,*coefficients)
    dargs=(R,ring,structure,*coefficients)
    alpha=call('weierstrass-coordinate-linear',*wargs)
    beta=call('weierstrass-coordinate-cubic',*wargs)
    elem=lambda p,q:f('#pt-construct','quadratic-element','()',seq([L]),'coordinates',seq([p,q]))
    norm=lambda p,q:call('coordinate-norm-degree-value',*wargs,p,q)
    square=lambda p:pm(p,p)
    crosspoly=lambda p,q:pm(pm(p,q),alpha)
    cubicpoly=lambda q:pm(square(q),beta)
    rawform=lambda p,q:pa(pa(square(p),pn(crosspoly(p,q))),pn(cubicpoly(q)))
    form=lambda p,q:call('coordinate-norm-degree-polynomial',*wargs,p,q)
    nlaw=lambda label,*args:call('coordinate-norm-degree-'+label,*wargs,*args)
    dlaw=lambda label,*args:call('coordinate-norm-degree-'+label,*dargs,*args)
    form_eq=lambda p,q:nlaw('formula',p,q)
    forms=[definition('coordinate-norm-degree-value',wparams+[(p,L),(q,L)],L,call('weierstrass-coordinate-norm',*wargs,elem(p,q))),
           definition('coordinate-norm-degree-polynomial',wparams+[(p,L),(q,L)],L,rawform(p,q)),
           theorem('coordinate-norm-degree-formula',wparams+[(p,L),(q,L)],pe(norm(p,q),form(p,q)),call('weierstrass-coordinate-norm-formula',*wargs,elem(p,q)))]
    d='leading-degree'
    forms.append(theorem('coordinate-norm-degree-transfer',wparams+[(p,L),(q,L),(d,N),('polynomial-degree',degree(form(p,q),d))],degree(norm(p,q),d),
                         law('degree-congruent',form(p,q),norm(p,q),d,psy(norm(p,q),form(p,q),form_eq(p,q)),'polynomial-degree')))
    r,t='other-constant-polynomial','other-linear-polynomial'
    cross_eq=plaw('multiply-congruent',pm(p,q),alpha,pm(r,t),alpha,
                 plaw('multiply-congruent',p,q,r,t,'constant-equation','linear-equation'),pr(alpha))
    cubic_eq=plaw('multiply-congruent',square(q),beta,square(t),beta,
                 plaw('multiply-congruent',q,q,t,t,'linear-equation','linear-equation'),pr(beta))
    proof=pac(pa(square(p),pn(crosspoly(p,q))),pn(cubicpoly(q)),pa(square(r),pn(crosspoly(r,t))),pn(cubicpoly(t)),
              pac(square(p),pn(crosspoly(p,q)),square(r),pn(crosspoly(r,t)),plaw('multiply-congruent',p,p,r,r,'constant-equation','constant-equation'),plaw('negate-congruent',crosspoly(p,q),crosspoly(r,t),cross_eq)),
              plaw('negate-congruent',cubicpoly(q),cubicpoly(t),cubic_eq))
    forms.append(theorem('coordinate-norm-degree-form-congruent',wparams+[(p,L),(q,L),(r,L),(t,L),('constant-equation',pe(p,r)),('linear-equation',pe(q,t))],pe(form(p,q),form(r,t)),proof))
    proof=pchain([norm(p,q),form(p,q),form(r,t),norm(r,t)],[form_eq(p,q),nlaw('form-congruent',p,q,r,t,'constant-equation','linear-equation'),psy(norm(r,t),form(r,t),form_eq(r,t))])
    forms.append(theorem('coordinate-norm-degree-congruent',wparams+[(p,L),(q,L),(r,L),(t,L),('constant-equation',pe(p,r)),('linear-equation',pe(q,t))],pe(norm(p,q),norm(r,t)),proof))
    write('coordinate-norm-degree-formula','; The norm here is the actual previously constructed\n; determinant norm, with its proved source polynomial formula.\n; Coefficient equivalence preserves it; degree transfers across that\n; formula, so later degree proofs concern the actual coordinate norm.',forms)

    certp,certq='constant-certificate','linear-certificate'
    sq_degree=lambda p,d,h:law('degree-product',structure,p,p,d,d,h,h)
    forms=[theorem('coordinate-norm-degree-square',wdomain+[(p,L),(dp,N),(certp,degree(p,dp))],degree(square(p),double(dp)),sq_degree(p,dp,certp))]
    beta_degree=call('ring-polynomial-degree-weierstrass-cubic',*dargs)
    forms.append(theorem('coordinate-norm-degree-cubic-term',wdomain+[(q,L),(dq,N),(certq,degree(q,dq))],degree(cubicpoly(q),cubic(dq)),
                         law('degree-product',structure,square(q),beta,double(dq),three,sq_degree(q,dq,certq),beta_degree)))
    first_upper=project('conjunction',0,law('product-top',p,q,dp,dq,'constant-support','linear-support'))
    linear_upper=call('ring-polynomial-degree-weierstrass-linear-bound',*dargs)
    cross_upper=project('conjunction',0,law('product-top',pm(p,q),alpha,nad(dp,dq),one,first_upper,linear_upper))
    forms.append(theorem('coordinate-norm-degree-cross-bound',wdomain+[(p,L),(q,L),(dp,N),(dq,N),('constant-support',support(p,succ(dp))),('linear-support',support(q,succ(dq)))],support(crosspoly(p,q),cross(dp,dq)),cross_upper))
    write('coordinate-norm-degree-term-bounds','; Prove the square and cubic-term degrees from actual\n; domain products, and the cross-term upper support from polynomial\n; multiplication and the actual Weierstrass linear bound. All input\n; leading degrees include0, and all curve coefficients remain arbitrary.',forms)

    # Explicit support weakening along proved gap equations.
    b,desired='original-bound','desired-bound'
    changed=law('support-weaken',p,b,g,'support')
    proof=sub(lam([('selected-bound',N)],support(p,'selected-bound')),nad(b,g),desired,
              nsy(desired,nad(b,g),'bound-equation'),changed)
    forms=[theorem('coordinate-norm-degree-weaken-support',base+[(p,L),(b,N),(g,N),(desired,N),('support',support(p,b)),('bound-equation',neq(desired,nad(b,g)))],support(p,desired),proof)]
    write('coordinate-norm-degree-support-gaps','; A proved natural gap equation weakens an actual\n; support bound to the exact desired index. No hidden inequality\n; conversion or polynomial leading-degree fact is assumed.',forms)
    weaken=lambda p,b,g,d,h,j:call('coordinate-norm-degree-weaken-support',R,ring,p,b,g,d,h,j)
    common=wdomain+[(p,L),(q,L),(dp,N),(dq,N),(g,N),(certp,degree(p,dp)),(certq,degree(q,dq))]
    square_upper=project('conjunction',1,dlaw('square',p,dp,certp))
    cross_upper=dlaw('cross-bound',p,q,dp,dq,project('conjunction',1,certp),project('conjunction',1,certq))
    sq_low=weaken(square(p),succ(double(dp)),double(g),cubic(dq),square_upper,call('coordinate-norm-degree-low-square-gap',dp,dq,g,'low-relation'))
    cr_low=weaken(crosspoly(p,q),cross(dp,dq),g,cubic(dq),cross_upper,call('coordinate-norm-degree-low-cross-gap',dp,dq,g,'low-relation'))
    lower=pa(square(p),pn(crosspoly(p,q)))
    lower_upper=law('support-add',square(p),pn(crosspoly(p,q)),cubic(dq),sq_low,law('support-negate',crosspoly(p,q),cubic(dq),cr_low))
    certificate=law('degree-subtract-right-dominant',lower,cubicpoly(q),cubic(dq),lower_upper,dlaw('cubic-term',q,dq,certq))
    forms=[theorem('coordinate-norm-degree-cubic-dominant',common+[('low-relation',low)],degree(norm(p,q),cubic(dq)),nlaw('transfer',p,q,cubic(dq),certificate))]
    write('coordinate-norm-degree-low-branch','; If dq+1=dp+gap, the square and cross terms have\n; support strictly below the cubic leading degree2*dq+3. Strict\n; subtraction dominance proves the actual norm has that degree,\n; including equality gap0 and degree-zero input polynomials.',forms)

    S,C,B=square(p),crosspoly(p,q),cubicpoly(q)
    pring=call('ring-polynomial-structure',R,ring)
    pop=lambda label,*args:call('ring-'+label,L,pring,*args)
    regroup=pa(S,pn(pa(C,B)))
    proof=pchain([form(p,q),pa(S,pa(pn(C),pn(B))),regroup],[
        plaw('add-associative',S,pn(C),pn(B)),
        pac(S,pa(pn(C),pn(B)),S,pn(pa(C,B)),pr(S),psy(pn(pa(C,B)),pa(pn(C),pn(B)),pop('negate-add',C,B)))])
    forms=[theorem('coordinate-norm-degree-regroup',wparams+[(p,L),(q,L)],pe(form(p,q),regroup),proof)]
