def f(*xs): return '(' + ' '.join(xs) + ')'
def seq(xs): return f(*xs)
def app(head, *xs): return f('#pt-app', head, *xs)
def use(name, levels=()): return f('#pt-use', name, seq(levels))
def call(name, *xs): return app(use(name), *xs)
def eq(a, b): return f('#pt-eq', '#pt-nat', a, b)
def succ(a): return f('#pt-succ', a)
def pi(bs, body): return f('#pt-pi', seq(f(n, ty) for n, ty in bs), body)
def lam(bs, body): return f('#pt-lambda', seq(f(n, ty) for n, ty in bs), body)
def add(a, b): return call('add', a, b)
def mul(a, b): return call('multiply', a, b)
def neg(p): return pi([('denied-proof', p)], '#pt-false')
def sym(a, b, h): return app(use('symmetry', ['0']), '#pt-nat', a, b, h)
def trans(a, b, c, h, j): return app(use('transitivity', ['0']), '#pt-nat', a, b, c, h, j)
def cong(fn, a, b, h): return app(use('congruence', ['0', '0']), '#pt-nat', '#pt-nat', fn, a, b, h)
def refl(a): return f('#pt-refl', '#pt-nat', a)
def theorem(name, bs, statement, proof):
    return f('#theorem', name, f('#universes'), f('#parameters', *(f('#parameter', n, ty) for n, ty in bs)), f('#statement', statement), f('#proof', proof))
def chain(points, proofs):
    assert len(points) == len(proofs) + 1
    result = proofs[-1]
    for i in range(len(proofs) - 2, -1, -1):
        result = trans(points[i], points[i+1], points[-1], proofs[i], result)
    return result
def lt(a, b): return call('less-than', a, b)
def spec(n, d, q, r): return call('division-spec', n, d, q, r)
