    forms.append(theorem('finite-list-tabulate-index',[(A,TYPE),(fn,fnty),(x,A),(count,N),('membership',member(A,x,table))],output(count),proof))
    prop=lambda n:equal(N,length(A,tab(A,fn,n)),n)
