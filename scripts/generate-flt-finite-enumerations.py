    forms.append(theorem('finite-list-map-no-duplicates',fnames+[('injectivity',injective),(xs,L(A)),('distinct',nodup(A,xs))],nodup(B,map_(A,B,fn,xs)),proof))
    prop=lambda values:equal(N,length(B,map_(A,B,fn,values)),length(A,values))
    proof=induct(A,xs,lam([('list-subject',L(A))],prop('list-subject')),TRIVIAL,
        lam([(h,A),(t,L(A)),(ih,prop(t))],congruence(N,N,lam([('length-value',N)],succ('length-value')),length(B,map_(A,B,fn,t)),length(A,t),ih)))
    forms.append(theorem('finite-list-map-length',fnames+[(xs,L(A))],prop(xs),proof))
    prop=lambda values:equal(N,length(A,append(A,values,ys)),call('add',length(A,values),length(A,ys)))
