    forms.append(theorem('finite-list-append-length',[(A,TYPE),(xs,L(A)),(ys,L(A))],prop(xs),proof))
    write('finite-list-map-laws','; Injective maps preserve absence of duplicates. Length laws are\n'
        '; structural induction proofs for actual mapped/appended lists.',forms)
    # A strict successor bound splits into its final index or an earlier one.
    index,limit,gap='index','limit','gap'
    out=either(equal(N,index,limit),lt(index,limit))
    gap_pred=lam([('candidate-gap',N)],equal(N,succ(limit),call('add',succ(index),'candidate-gap')))
    base_eq=transitive(N,succ(limit),call('add',succ(index),ZERO),succ(index),'gap-equation',call('add-zero-right',succ(index)))
