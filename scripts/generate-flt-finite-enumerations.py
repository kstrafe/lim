    witness=introduce(N,lam([('candidate-gap',N)],equal(N,limit,call('add',succ(index),'candidate-gap'))),earlier,path)
    step=lam([(earlier,N),('unused-earlier',pi([('earlier-equation',equal(N,succ(limit),call('add',succ(index),earlier)))],out)),
        ('gap-equation',following)],choose_right(equal(N,index,limit),lt(index,limit),witness))
    proof=app(f('#pt-nat-induct',lam([('gap-index',N)],pi([('position',equal(N,succ(limit),call('add',succ(index),'gap-index')))],out)),
        base,step,gap),'gap-position')
