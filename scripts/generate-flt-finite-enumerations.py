#!/usr/bin/env python3
"""Author native finite-list and finite-enumeration proofs for the FLT port.

Every emitted term is checked by Lim. This writer supplies no trusted
mathematical judgments and is not required to check the generated sources.
"""
import argparse
import importlib.util
import re
from pathlib import Path

_spec = importlib.util.spec_from_file_location('enumeration_syntax',
    Path(__file__).with_name('generate-flt-finite-residues.py'))
_syntax = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_syntax)
f, seq, app, use, pi, lam = (_syntax.f, _syntax.seq, _syntax.app,
    _syntax.use, _syntax.pi, _syntax.lam)
N, PROP, TYPE = '#pt-nat', '#pt-prop', '(#pt-type 0)'
ZERO = '#pt-zero'
FALSE = '#pt-false'

def call(name, *args): return app(use(name), *args) if args else use(name)
def equal(ty, x, y): return f('#pt-eq', ty, x, y)
def reflexive(ty, x): return f('#pt-refl', ty, x)
def symmetry(ty, x, y, h): return app(use('symmetry',['0']),ty,x,y,h)
def transitive(ty,x,y,z,h,j): return app(use('transitivity',['0']),ty,x,y,z,h,j)
def congruence(ta,tb,fn,x,y,h): return app(use('congruence',['0','0']),ta,tb,fn,x,y,h)
def substitute(ty,pred,x,y,h,proof): return app(use('substitution',['0']),ty,pred,x,y,h,proof)
def definition(name,params,result,body): return f('#math-definition',name,'()',pi(params,result),lam(params,body))
def theorem(name,params,statement,proof): return _syntax.theorem(name,params,statement,proof)
def neg(p): return pi([('denied-evidence',p)],FALSE)
def both(p,q): return call('conjunction',p,q)
def pair(p,q,h,j): return call('conjunction-introduce',p,q,h,j)
def left(h): return f('#pt-project','conjunction','0',h)
def right(h): return f('#pt-project','conjunction','1',h)
def either(p,q): return call('disjunction',p,q)
def choose_left(p,q,h): return call('disjunction-left',p,q,h)
def choose_right(p,q,h): return call('disjunction-right',p,q,h)
def cases(p,q,result,lh,rh,h): return call('disjunction-eliminate',p,q,result,lh,rh,h)
def exists(ty,pred): return app(use('exists',['0']),ty,pred)
def introduce(ty,pred,value,proof): return f('#pt-construct','exists','(0)',seq([ty,pred]),'introduce',seq([value,proof]))
def eliminate(ty,pred,subject,result,params,body):
    return f('#pt-induct','exists','(0)',seq([ty,pred]),lam([('existential-subject',exists(ty,pred))],result),seq([lam(params,body)]),subject)
def absurd(result,h): return call('false-elimination',result,h)
def lt(x,y): return call('less-than',x,y)
def succ(x): return f('#pt-succ',x)
TRUE = equal(N,ZERO,ZERO)
TRIVIAL = reflexive(N,ZERO)

def generated_sources():
    root=Path(__file__).resolve().parent.parent/'theorems'/'flt'
    outputs={}
    aliases={'add':'../fermat_statement','multiply':'../fermat_statement'}
    for module in ['equality','logic-exists','logic-false','logical-connectives',
        'natural-order','natural-addition','natural-successor','natural-nonzero','natural-discrete-order',
        'finite-residue-defs','finite-residue-extensional','finite-residue-semiring','logical-decision',
        'finite-weierstrass-reduction','finite-weierstrass-points','finite-weierstrass-point-decisions',
        'integer-defs','integer-weierstrass-defs','weierstrass-model-equivalence','natural-prime']:
        for name in re.findall(r'^\(#(?:theorem|math-definition|math-inductive) ([^\s()]+)',(root/(module+'.lim')).read_text(),re.M):
            aliases[name]=module
    def write(module,comment,forms):
        body='\n\n'.join(forms)+'\n'
        tokens=set(re.findall(r'[^()\s]+',body))
        imports=''.join(f'(#alias {name} = ./{owner}.lim::{name})\n' for name,owner in aliases.items() if name in tokens and owner!=module)
        outputs[module]='; Generated by scripts/generate-flt-finite-enumerations.py; checked native proof terms.\n'+comment+'\n'+imports+'\n'+body
        for name in re.findall(r'^\(#(?:theorem|math-definition|math-inductive) ([^\s()]+)',body,re.M): aliases[name]=module

    A,B='Element','Image'
    def L(ty): return call('finite-list',ty)
    def nil(ty): return f('#pt-construct','finite-list','()',seq([ty]),'nil','()')
    def cons(ty,h,t): return f('#pt-construct','finite-list','()',seq([ty]),'cons',seq([h,t]))
    def length(ty,xs): return call('finite-list-length',ty,xs)
    def append(ty,xs,ys): return call('finite-list-append',ty,xs,ys)
    def map_(ta,tb,fn,xs): return call('finite-list-map',ta,tb,fn,xs)
    def member(ty,x,xs): return call('finite-list-member',ty,x,xs)
    def nodup(ty,xs): return call('finite-list-no-duplicates',ty,xs)
    def induct(ty,subject,motive,base,step):
        return f('#pt-induct','finite-list','()',seq([ty]),motive,seq([base,step]),subject)
    x,y,xs,ys='needle','other','values','other-values'
    h,t,ih='list-head','list-tail','tail-result'
    record=f('#math-inductive','finite-list','()',seq([f('Element',TYPE)]),TYPE,
        seq([seq(['nil','()']),seq(['cons',seq([f('head','Element'),f('tail',L('Element'))])])]))
    forms=[record]
    body=induct(A,xs,lam([('list-subject',L(A))],N),ZERO,
        lam([(h,A),(t,L(A)),(ih,N)],succ(ih)))
    forms.append(definition('finite-list-length',[(A,TYPE),(xs,L(A))],N,body))
    body=induct(A,xs,lam([('list-subject',L(A))],L(A)),ys,
        lam([(h,A),(t,L(A)),(ih,L(A))],cons(A,h,ih)))
    forms.append(definition('finite-list-append',[(A,TYPE),(xs,L(A)),(ys,L(A))],L(A),body))
    fn='function'; fnty=pi([('function-input',A)],B)
    body=induct(A,xs,lam([('list-subject',L(A))],L(B)),nil(B),
        lam([(h,A),(t,L(A)),(ih,L(B))],cons(B,app(fn,h),ih)))
    forms.append(definition('finite-list-map',[(A,TYPE),(B,TYPE),(fn,fnty),(xs,L(A))],L(B),body))
    body=induct(A,xs,lam([('list-subject',L(A))],PROP),FALSE,
        lam([(h,A),(t,L(A)),(ih,PROP)],either(equal(A,x,h),ih)))
    forms.append(definition('finite-list-member',[(A,TYPE),(x,A),(xs,L(A))],PROP,body))
    body=induct(A,xs,lam([('list-subject',L(A))],PROP),TRUE,
        lam([(h,A),(t,L(A)),(ih,PROP)],both(neg(member(A,h,t)),ih)))
    forms.append(definition('finite-list-no-duplicates',[(A,TYPE),(xs,L(A))],PROP,body))
    head_member=choose_left(equal(A,x,x),member(A,x,xs),reflexive(A,x))
    forms.append(theorem('finite-list-member-head',[(A,TYPE),(x,A),(xs,L(A))],member(A,x,cons(A,x,xs)),head_member))
    forms.append(theorem('finite-list-member-tail',[(A,TYPE),(x,A),(y,A),(xs,L(A)),('membership',member(A,x,xs))],
        member(A,x,cons(A,y,xs)),choose_right(equal(A,x,y),member(A,x,xs),'membership')))
    forms.append(theorem('finite-list-nil-no-duplicates',[(A,TYPE)],nodup(A,nil(A)),TRIVIAL))
    forms.append(theorem('finite-list-cons-no-duplicates',[(A,TYPE),(x,A),(xs,L(A)),
        ('fresh',neg(member(A,x,xs))),('distinct-tail',nodup(A,xs))],nodup(A,cons(A,x,xs)),
        pair(neg(member(A,x,xs)),nodup(A,xs),'fresh','distinct-tail')))
    write('finite-list-defs','; Concrete Type-0 lists, membership, length, map, append and absence\n'
        '; of duplicates. Recursors compute from the actual constructors.',forms)

    pred=lam([('member-value',A)],member(A,'member-value',xs))
    proof=substitute(A,pred,x,y,'equation','membership')
    forms=[theorem('finite-list-member-congruent',[(A,TYPE),(x,A),(y,A),(xs,L(A)),
        ('equation',equal(A,x,y)),('membership',member(A,x,xs))],member(A,y,xs),proof)]
    fnames=[(A,TYPE),(B,TYPE),(fn,fnty)]
    prop=lambda values:pi([('source-membership',member(A,x,values))],member(B,app(fn,x),map_(A,B,fn,values)))
    base=lam([('source-membership',FALSE)],absurd(member(B,app(fn,x),nil(B)),'source-membership'))
    result=member(B,app(fn,x),cons(B,app(fn,h),map_(A,B,fn,t)))
    eq_head=equal(A,x,h); tail_member=member(A,x,t)
    lh=lam([('head-equation',eq_head)],choose_left(equal(B,app(fn,x),app(fn,h)),member(B,app(fn,x),map_(A,B,fn,t)),
        congruence(A,B,fn,x,h,'head-equation')))
    rh=lam([('tail-membership',tail_member)],choose_right(equal(B,app(fn,x),app(fn,h)),member(B,app(fn,x),map_(A,B,fn,t)),app(ih,'tail-membership')))
    step=lam([(h,A),(t,L(A)),(ih,prop(t)),('source-membership',member(A,x,cons(A,h,t)))],
        cases(eq_head,tail_member,result,lh,rh,'source-membership'))
    proof=app(induct(A,xs,lam([('list-subject',L(A))],prop('list-subject')),base,step),'membership')
    forms.append(theorem('finite-list-map-member',fnames+[(x,A),(xs,L(A)),('membership',member(A,x,xs))],
        member(B,app(fn,x),map_(A,B,fn,xs)),proof))
    # Recover a source member from a mapped list using Prop elimination only.
    needle='image-value'; witness='source-value'; packet='source-packet'
    pair_pred=lambda values,w:both(member(A,w,values),equal(B,needle,app(fn,w)))
    wp=lambda values:lam([('candidate-source',A)],pair_pred(values,'candidate-source'))
    out=lambda values:exists(A,wp(values))
    prop=lambda values:pi([('mapped-membership',member(B,needle,map_(A,B,fn,values)))],out(values))
    base=lam([('mapped-membership',FALSE)],absurd(out(nil(A)),'mapped-membership'))
    lh=lam([('head-equation',equal(B,needle,app(fn,h)))],introduce(A,wp(cons(A,h,t)),h,
        pair(member(A,h,cons(A,h,t)),equal(B,needle,app(fn,h)),call('finite-list-member-head',A,h,t),'head-equation')))
    inner=introduce(A,wp(cons(A,h,t)),witness,pair(member(A,witness,cons(A,h,t)),equal(B,needle,app(fn,witness)),
        call('finite-list-member-tail',A,witness,h,t,left(packet)),right(packet)))
    recovered=eliminate(A,wp(t),app(ih,'tail-membership'),out(cons(A,h,t)),[(witness,A),(packet,pair_pred(t,witness))],inner)
    rh=lam([('tail-membership',member(B,needle,map_(A,B,fn,t)))],recovered)
    step=lam([(h,A),(t,L(A)),(ih,prop(t)),('mapped-membership',member(B,needle,map_(A,B,fn,cons(A,h,t))))],
        cases(equal(B,needle,app(fn,h)),member(B,needle,map_(A,B,fn,t)),out(cons(A,h,t)),lh,rh,'mapped-membership'))
    proof=app(induct(A,xs,lam([('list-subject',L(A))],prop('list-subject')),base,step),'membership')
    forms.append(theorem('finite-list-map-preimage',fnames+[(needle,B),(xs,L(A)),('membership',member(B,needle,map_(A,B,fn,xs)))],out(xs),proof))
    write('finite-list-membership','; Membership transports along actual identities. Mapped membership\n'
        '; has a proved source witness; no witness is extracted into data.',forms)

    forms=[]
    injective=pi([('injective-first',A),('injective-second',A),
        ('image-equation',equal(B,app(fn,'injective-first'),app(fn,'injective-second')))],equal(A,'injective-first','injective-second'))
    prop=lambda values:pi([('source-distinct',nodup(A,values))],nodup(B,map_(A,B,fn,values)))
    base=lam([('source-distinct',TRUE)],TRIVIAL)
    witness='preimage'; packet='preimage-packet'
    pre_pred=lam([('candidate-preimage',A)],both(member(A,'candidate-preimage',t),equal(B,app(fn,h),app(fn,'candidate-preimage'))))
    eq_h_w=app('injectivity',h,witness,right(packet))
    membership=substitute(A,lam([('member-value',A)],member(A,'member-value',t)),witness,h,
        symmetry(A,h,witness,eq_h_w),left(packet))
    contradiction=app(left('source-distinct'),membership)
    no_map_member=lam([('mapped-head-membership',member(B,app(fn,h),map_(A,B,fn,t)))],
        eliminate(A,pre_pred,call('finite-list-map-preimage',A,B,fn,app(fn,h),t,'mapped-head-membership'),FALSE,
            [(witness,A),(packet,both(member(A,witness,t),equal(B,app(fn,h),app(fn,witness))))],contradiction))
    step=lam([(h,A),(t,L(A)),(ih,prop(t)),('source-distinct',nodup(A,cons(A,h,t)))],
        pair(neg(member(B,app(fn,h),map_(A,B,fn,t))),nodup(B,map_(A,B,fn,t)),no_map_member,app(ih,right('source-distinct'))))
