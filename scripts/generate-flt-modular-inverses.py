from pathlib import Path

_spec = importlib.util.spec_from_file_location('inverse_syntax',
    Path(__file__).with_name('generate-flt-finite-residues.py'))
_syntax = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_syntax)
f, seq, app, use, pi, lam, theorem = (_syntax.f, _syntax.seq, _syntax.app,
    _syntax.use, _syntax.pi, _syntax.lam, _syntax.theorem)
N, TYPE, FALSE, ZERO = '#pt-nat', '(#pt-type 0)', '#pt-false', '#pt-zero'

def call(name,*args): return app(use(name),*args) if args else use(name)
def definition(name,params,result,body): return f('#math-definition',name,'()',pi(params,result),lam(params,body))
def eq(ty,x,y): return f('#pt-eq',ty,x,y)
def refl(ty,x): return f('#pt-refl',ty,x)
def succ(x): return f('#pt-succ',x)
def lt(x,y): return call('less-than',x,y)
def neg(p): return pi([('denied-proof',p)],FALSE)
def project(family,index,obj): return f('#pt-project',family,str(index),obj)
def false_into(ty,h): return f('#pt-induct','#pt-false','()','()',lam([('empty-evidence',FALSE)],ty),'()',h)
def sym(ty,x,y,h): return app(use('symmetry',['0']),ty,x,y,h)
def nat_induct(motive,base,step,subject): return f('#pt-nat-induct',motive,base,step,subject)
def let(name,ty,value,body): return f('#pt-let',f('#parameter',name,ty),value,body)

