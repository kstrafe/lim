#!/usr/bin/env python3
"""Author explicit checked Lim proofs for affine point operations.

Only syntax is generated. Every integer identity, cast, nonsingularity proof
and actual point operation is independently checked by Lim's native kernel.
"""
import argparse
import importlib.util
import re
import sys
from pathlib import Path

def load(name,file):
    spec=importlib.util.spec_from_file_location(name,Path(__file__).with_name(file))
    module=importlib.util.module_from_spec(spec)
    sys.modules[name]=module
    spec.loader.exec_module(module)
    return module

_syntax=load('affine_point_syntax','generate-flt-finite-residues.py')
_integer=load('affine_integer_syntax','generate-flt-eisenstein-algebra.py')
f,seq,app,use,pi,lam,theorem=(_syntax.f,_syntax.seq,_syntax.app,_syntax.use,_syntax.pi,_syntax.lam,_syntax.theorem)
N,TYPE,FALSE,ZERO='#pt-nat','(#pt-type 0)','#pt-false','#pt-zero'
def call(name,*args):return app(use(name),*args) if args else use(name)
def definition(name,params,result,body):return f('#math-definition',name,'()',pi(params,result),lam(params,body))
def eq(ty,x,y):return f('#pt-eq',ty,x,y)
def refl(ty,x):return f('#pt-refl',ty,x)
def neg(p):return pi([('denied-evidence',p)],FALSE)
def project(family,index,obj):return f('#pt-project',family,str(index),obj)
def subst(ty,pred,x,y,h,p):return app(use('substitution',['0']),ty,pred,x,y,h,p)
def sym(ty,x,y,h):return app(use('symmetry',['0']),ty,x,y,h)
def trans(ty,x,y,z,h,j):return app(use('transitivity',['0']),ty,x,y,z,h,j)

add,mul,negative=_integer.add,_integer.mul,_integer.negative
def difference(a,b):return add(a,negative(b))
def power(a,n):return 1 if n==0 else mul(a,power(a,n-1))
def neg_y(a1,a3,x,y):return difference(difference(negative(y),mul(a1,x)),a3)
def curve_polynomial(a1,a2,a3,a4,a6,x,y):
    return difference(add(add(power(y,2),mul(mul(a1,x),y)),mul(a3,y)),
        add(add(add(power(x,3),mul(a2,power(x,2))),mul(a4,x)),a6))
def derivative_x(a1,a2,a4,x,y):return difference(mul(a1,y),add(add(mul(3,power(x,2)),mul(mul(2,a2),x)),a4))
def derivative_y(a1,a3,x,y):return add(add(mul(2,y),mul(a1,x)),a3)
def add_x(a1,a2,x1,x2,l):return difference(difference(difference(add(power(l,2),mul(a1,l)),a2),x1),x2)
def line_value(x,y,l,t):return add(mul(l,difference(t,x)),y)
def cubic_value(c2,c1,c0,t):return add(negative(power(t,3)),add(add(mul(c2,power(t,2)),mul(c1,t)),c0))
def cubic_derivative(c2,c1,t):return add(add(negative(mul(3,power(t,2))),mul(mul(2,c2),t)),c1)
def cubic_quotient(c2,c1,x,t):
    return difference(add(c1,mul(c2,add(x,t))),add(add(power(x,2),mul(x,t)),power(t,2)))
def line_coefficients(a1,a2,a3,a4,a6,b,l):
    return (difference(add(power(l,2),mul(a1,l)),a2),
        difference(add(mul(add(mul(2,b),a3),l),mul(a1,b)),a4),
        difference(add(power(b,2),mul(a3,b)),a6))

def generated_sources():
    root=Path(__file__).resolve().parent.parent/'theorems'/'flt'
