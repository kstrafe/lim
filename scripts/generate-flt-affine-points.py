    def D(a,b):return call('finite-residue-difference',q,pos,a,b)
    def C(a):return call('finite-residue-of-integer',q,pos,a)
    def rn(n):return call('finite-residue-of-natural',q,pos,f('#pt-numeral',str(n)))
    def law(name,*args):return call('finite-residue-'+name,q,pos,*args)
    def ac(a,b,c,d,h,j):return law('add-congruent',a,b,c,d,h,j)
    def mc(a,b,c,d,h,j):return law('multiply-congruent',a,b,c,d,h,j)
    def nc(a,b,h):return law('negate-congruent',a,b,h)
    def dc(a,b,c,d,h,j):return law('difference-congruent',a,b,c,d,h,j)
    def render_f(expr):
        if isinstance(expr,str):return expr
