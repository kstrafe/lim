        'natural-order','finite-residue-defs','finite-residue-semiring','finite-residue-operations',
        'finite-residue-negation','finite-residue-powers','finite-residue-congruence-laws','finite-residue-cancellation',
        'finite-residue-multiplicative-signs','finite-residue-differences','finite-residue-extensional',
