    rpoly='third-polynomial'
    qrefl=lambda p:call('quadratic-quotient-evaluations-equal',*args(p,p,qr(image(p))))
    forms=[theorem('quadratic-quotient-reflexive',params+[(p,L)],equivalent(p,p),qrefl(p))]
    sym=call('quadratic-quotient-equal-evaluations',*args(p,q,'quotient-equation'))
    forms.append(theorem('quadratic-quotient-symmetric',params+[(p,L),(q,L),('quotient-equation',equivalent(p,q))],equivalent(q,p),
                         call('quadratic-quotient-evaluations-equal',*args(q,p,qy(image(p),image(q),sym)))))
    trans=qt(image(p),image(q),image(rpoly),call('quadratic-quotient-equal-evaluations',*args(p,q,'first-equation')),
             call('quadratic-quotient-equal-evaluations',*args(q,rpoly,'second-equation')))
