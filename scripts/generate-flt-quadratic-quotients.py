def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent / 'theorems' / 'flt'
    outputs = generated_sources()
    assert len(outputs) <= 48 and sum(len(t.encode()) for t in outputs.values()) <= 8*1024*1024
    tokens = lambda t: re.findall(r'[()]|[^()\s]+', re.sub(r';[^\n]*', '', t))
    comments = lambda t: [line.strip() for line in t.splitlines() if line.lstrip().startswith(';')]
    for module, text in outputs.items():
        path = root / (module + '.lim')
        old = path.read_text() if path.exists() else ''
        same = tokens(old) == tokens(text) and comments(old) == comments(text)
        if args.check and not same:
            raise SystemExit(f'{path}: generated source differs')
        if not args.check and not same:
            path.write_text(text)


if __name__ == '__main__':
    main()
