    write('ring-ideal-data','; Actual ideals are saturated membership predicates with\n; checked zero/additive/negation/multiplication closures. Equality is\n; mutual inclusion, so no function-extensionality or set equality axiom\n; is introduced. Right multiplication follows from commutativity.',forms)

