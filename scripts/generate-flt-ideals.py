    forms.append(theorem('ring-ideal-equal-transitive',base+[(I,IT),(J,IT),(K,IT),('first-equation',ieq(I,J)),('second-equation',ieq(J,K))],ieq(I,K),proof))
    write('ring-ideal-equivalence','; Prove inclusion transitivity and extensional ideal\n; equality reflexive/symmetric/transitive from explicit membership\n; maps, not kernel identity or a set-extensionality principle.',forms)

