    forms.append(theorem('ring-ideal-subset-transitive',base+[(I,IT),(J,IT),(K,IT),('first-inclusion',subset(I,J)),('second-inclusion',subset(J,K))],subset(I,K),proof))
    forms.append(theorem('ring-ideal-equal-reflexive',base+[(I,IT)],ieq(I,I),pair(subset(I,I),subset(I,I),identity,identity)))
