           theorem('ring-ideal-bottom-least',base+[(I,IT)],subset(bottom,I),
                   lam([(a,R),('zero-equation',E(a,Z))],ilaw('member-congruent',I,Z,a,ss(a,Z,'zero-equation'),ilaw('zero',I)))),
           theorem('ring-ideal-top-greatest',base+[(I,IT)],subset(I,top),lam([(a,R),('member',mem(I,a))],yes)),
