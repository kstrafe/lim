mod support;

use std::fs;

fn compile(
    source: &str,
    path: &std::path::Path,
    scratch: &support::Scratch,
    config: &lim::CompileConfig,
) -> Result<String, lim::Diagnostic> {
    lim::compile_source_to_assembly(
        source,
        path,
        config,
        &scratch.path().join("cache"),
        lim::TargetDescription::X86_64_SYSTEM_V,
    )
}

#[test]
fn external_import_prefix_is_the_producer_identity_under_cfg_and_cache() {
    let scratch = support::Scratch::new("provenance-import-prefix");
    fs::write(
        scratch.path().join("producer.lim"),
        "(#gn make (name) `((#struct ,name () ())))
         (#cfg-if (#cfg-is #extra yes) (@make Thing))",
    )
    .unwrap();

    let source = "(#import-external \"producer.lim\" ext-)
      (#cfg-if (#cfg-is #extra yes) (#require-generated ext-Thing ext-make))
      (#fn main () #u64 (#return 0u64))";
    for extra in ["no", "yes"] {
        let mut config = lim::CompileConfig::default();
        config.set("extra", extra);
        for _ in 0..2 {
            compile(source, &scratch.path().join("main.lim"), &scratch, &config)
                .unwrap_or_else(|error| panic!("extra={extra}: {error:?}"));
        }
    }
}

#[test]
fn imported_consumer_requirement_keeps_its_source_span_and_rendered_hunk() {
    let scratch = support::Scratch::new("provenance-import-diagnostic");
    let module = "(#gn make (name) `((#struct ,name () ())))
      (@make Actual)
      (#require-generated Wanted make)";
    let module_path = scratch.path().join("consumer.lim");
    fs::write(&module_path, module).unwrap();
    let root = "(#import \"consumer.lim\")
      (#fn main () #u64 (#return 0u64))";
    let error = compile(
        root,
        &scratch.path().join("main.lim"),
        &scratch,
        &lim::CompileConfig::default(),
    )
    .unwrap_err();

    assert_eq!(error.code, lim::DiagnosticCode::Generator, "{error:?}");
    assert!(
        error
            .message
            .contains("'Wanted' was not generated by '@make'"),
        "{error:?}"
    );
    assert_eq!(error.source_name.as_deref(), module_path.to_str());
    let span = error
        .span
        .expect("requirement name should be source-spanned");
    assert_eq!(&module[span.start..span.end], "Wanted");
    let rendered = lim::render_diagnostic(&error, module, module_path.to_str().unwrap());
    assert!(rendered.contains("Wanted"), "{rendered}");
    assert!(rendered.contains('^'), "{rendered}");
}

#[test]
fn duplicate_inner_builtin_output_retains_each_wrapper_origin_cold_and_warm() {
    let scratch = support::Scratch::new("provenance-import-wrappers");
    let source = "(#gn make (name) `((@#optional (: type #u64 : name ,name))))
      (#gn wrappera () `((@make nameMaybe)))
      (#gn wrapperb () `((@make nameMaybe)))
      (@wrappera) (@wrapperb)
      (#require-generated nameMaybe #optional (nameMaybe-some nameMaybe-none nameMaybe-construct))
      (#require-generated nameMaybe wrappera (nameMaybe-some nameMaybe-none))
      (#require-generated nameMaybe wrapperb (nameMaybe-some nameMaybe-none))
      (#fn main () #u64 (#return 0u64))";
    for _ in 0..2 {
        compile(
            source,
            &scratch.path().join("main.lim"),
            &scratch,
            &lim::CompileConfig::default(),
        )
        .unwrap();
    }
}
