mod support;

fn compile(source: &str, scratch: &support::Scratch) -> Result<String, lim::Diagnostic> {
    lim::compile_source_to_assembly(
        source,
        &scratch.path().join("main.lim"),
        &lim::CompileConfig::default(),
        &scratch.path().join("cache"),
        lim::TargetDescription::X86_64_SYSTEM_V,
    )
}

const PRODUCER: &str = "(#gn make (name variant)
    `((#enum ,name () ((,variant #u64)))))";

#[test]
fn forward_requirements_validate_fresh_and_cached_outputs() {
    let scratch = support::Scratch::new("provenance-cache");
    let source = format!(
        "{PRODUCER}
      (#require-generated Value make (Value::Ready))
      (@make Value Value::Ready)
      (#fn main () #u64 (#return (#match (Value::Ready 42u64)
        (#case (Value::Ready answer) answer))))"
    );
    let first = compile(&source, &scratch).unwrap();
    assert_eq!(first, compile(&source, &scratch).unwrap());
}

#[test]
fn matching_names_do_not_forge_generator_origin() {
    for declaration in [
        "(#struct Fake () ())",
        "(#gn counterfeit () `((#struct Fake () ()))) (@counterfeit)",
    ] {
        let source = format!(
            "{PRODUCER} {declaration}
          (#require-generated Fake make) (#fn main () #u64 (#return 0u64))"
        );
        let error = compile(&source, &support::Scratch::new("provenance-forgery")).unwrap_err();
        assert_eq!(error.code, lim::DiagnosticCode::Generator);
        assert!(
            error.message.contains("was not generated by '@make'"),
            "{error:?}"
        );
        let span = error.span.unwrap();
        assert_eq!(&source[span.start..span.end], "Fake");
    }
}

#[test]
fn companions_from_different_invocations_are_rejected() {
    let source = format!(
        "{PRODUCER}
      (@make First First::Ready) (@make Second Second::Ready)
      (#require-generated First make (Second::Ready))
      (#fn main () #u64 (#return 0u64))"
    );
    let error = compile(&source, &support::Scratch::new("provenance-mixed")).unwrap_err();
    assert!(
        error.message.contains("same '@make' invocation"),
        "{error:?}"
    );
    let span = error.span.unwrap();
    assert_eq!(&source[span.start..span.end], "Second::Ready");
}

#[test]
fn duplicate_nested_invocations_keep_both_wrapper_origins() {
    let source = format!(
        "{PRODUCER}
      (#gn first () `((@make Value Value::Ready)))
      (#gn second () `((@make Value Value::Ready)))
      (@first) (@second)
      (#require-generated Value make (Value::Ready))
      (#require-generated Value first (Value::Ready))
      (#require-generated Value second (Value::Ready))
      (#fn main () #u64 (#return 42u64))"
    );
    let scratch = support::Scratch::new("provenance-wrappers");
    for _ in 0..2 {
        compile(&source, &scratch).unwrap();
    }
}

#[test]
fn builtin_output_and_its_wrappers_have_checked_origins() {
    let source = "(#gn wrap () `((@#optional (: type #u64 : name Maybe))))
      (@wrap)
      (#require-generated Maybe #optional (Maybe-some Maybe-none Maybe-construct))
      (#require-generated Maybe wrap (Maybe-some Maybe-none))
      (#fn main () #u64 (#return 42u64))";
    let scratch = support::Scratch::new("provenance-builtin");
    for _ in 0..2 {
        compile(source, &scratch).unwrap();
    }
}

#[test]
fn async_companions_can_be_registered_in_a_distributed_enum() {
    let source = include_str!("../examples/future_registration.lim");
    let scratch = support::Scratch::new("provenance-async");
    for _ in 0..2 {
        compile(source, &scratch).unwrap();
    }
    // Variant identifiers are global. Registering one future in two executor
    // enums must qualify the variants by their respective executor roots.
    let two_executors = format!(
        "{source}\n(#distributed-enum OtherExecutor ())
        (@register-future OtherExecutor Work)"
    );
    compile(&two_executors, &scratch).unwrap();
    let wrong_producer = source.replacen("#async-fn-pinned", "#optional", 1);
    assert_ne!(wrong_producer, source);
    let error = compile(&wrong_producer, &scratch).unwrap_err();
    assert_eq!(error.code, lim::DiagnosticCode::Generator);
    assert!(
        error.message.contains("was not generated by '@#optional'"),
        "{error:?}"
    );
}

#[test]
fn malformed_requirements_are_source_spanned() {
    for form in [
        "(#require-generated)",
        "(#require-generated Value)",
        "(#require-generated 1 producer)",
        "(#require-generated Value producer 42)",
        "(#require-generated Value producer (#u64))",
    ] {
        let error = compile(form, &support::Scratch::new("provenance-invalid")).unwrap_err();
        assert_eq!(error.code, lim::DiagnosticCode::Generator);
        assert!(error.span.is_some());
    }
}
